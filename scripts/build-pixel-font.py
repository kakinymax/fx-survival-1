import re
from pathlib import Path
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

root = Path(__file__).resolve().parents[1] / 'dist' / 'fonts'
source = (root.parent / 'market-raster.js').read_text().split('export class Raster')[0]
patterns = {key: ast.literal_eval(rows) for key, rows in re.findall(r"'([^']+)':(\[[^\]]+\])", source)}
# Lowercase and punctuation retain their meaning in names and version labels.
patterns.update({
 'a':['00000','00000','01110','00001','01111','10001','01111'],
 'b':['10000','10000','10110','11001','10001','10001','11110'],
 'c':['00000','00000','01110','10000','10000','10001','01110'],
 'd':['00001','00001','01101','10011','10001','10001','01111'],
 'e':['00000','00000','01110','10001','11111','10000','01110'],
 'f':['00110','01001','01000','11100','01000','01000','01000'],
 'g':['00000','01111','10001','10001','01111','00001','01110'],
 'h':['10000','10000','10110','11001','10001','10001','10001'],
 'i':['00100','00000','01100','00100','00100','00100','01110'],
 'j':['00010','00000','00110','00010','00010','10010','01100'],
 'k':['10000','10000','10010','10100','11000','10100','10010'],
 'l':['01100','00100','00100','00100','00100','00100','01110'],
 'm':['00000','00000','11010','10101','10101','10001','10001'],
 'n':['00000','00000','10110','11001','10001','10001','10001'],
 'o':['00000','00000','01110','10001','10001','10001','01110'],
 'p':['00000','11110','10001','10001','11110','10000','10000'],
 'q':['00000','01111','10001','10001','01111','00001','00001'],
 'r':['00000','00000','10110','11001','10000','10000','10000'],
 's':['00000','00000','01111','10000','01110','00001','11110'],
 't':['01000','01000','11100','01000','01000','01001','00110'],
 'u':['00000','00000','10001','10001','10001','10011','01101'],
 'v':['00000','00000','10001','10001','10001','01010','00100'],
 'w':['00000','00000','10001','10001','10101','10101','01010'],
 'x':['00000','00000','10001','01010','00100','01010','10001'],
 'y':['00000','10001','10001','10001','01111','00001','01110'],
 'z':['00000','00000','11111','00010','00100','01000','11111'],
 '!':['00100','00100','00100','00100','00100','00000','00100'],
 '?':['01110','10001','00001','00010','00100','00000','00100'],
 ',':['00000','00000','00000','00000','00110','00100','01000'],
 ';':['00000','00110','00110','00000','00110','00100','01000'],
 '(':['00010','00100','01000','01000','01000','00100','00010'],
 ')':['01000','00100','00010','00010','00010','00100','01000'],
 '[':['01110','01000','01000','01000','01000','01000','01110'],
 ']':['01110','00010','00010','00010','00010','00010','01110'],
 '_':['00000','00000','00000','00000','00000','00000','11111'],
 '=':['00000','00000','11111','00000','11111','00000','00000'],
 '<':['00001','00010','00100','01000','00100','00010','00001'],
 '>':['10000','01000','00100','00010','00100','01000','10000'],
 '#':['01010','01010','11111','01010','11111','01010','01010'],
 '*':['00000','10101','01110','11111','01110','10101','00000'],
 '|':['00100','00100','00100','00100','00100','00100','00100'],
 "'":['00100','00100','00000','00000','00000','00000','00000'],
 '"':['01010','01010','00000','00000','00000','00000','00000'],
 '@':['01110','10001','10111','10101','10111','10000','01110'],
 '$':['00100','01111','10100','01110','00101','11110','00100'],
 '&':['01100','10010','10100','01000','10101','10010','01101'],
 '^':['00100','01010','10001','00000','00000','00000','00000'],
 '`':['01000','00100','00000','00000','00000','00000','00000'],
 '~':['00000','00000','01001','10110','00000','00000','00000'],
 '{':['00010','00100','00100','01000','00100','00100','00010'],
 '}':['01000','00100','00100','00010','00100','00100','01000'],
 '\\':['10000','10000','01000','00100','00010','00001','00001'],
})
assert all(chr(code) in patterns for code in range(32,127))
fb = FontBuilder(1024, isTTF=True)
names = {ord(c): f'uni{ord(c):04X}' for c in patterns}
order = ['.notdef'] + list(names.values())
fb.setupGlyphOrder(order)
fb.setupCharacterMap(names)
glyphs = {'.notdef': TTGlyphPen(None).glyph()}
for char, rows in patterns.items():
    pen = TTGlyphPen(None)
    for y, row in enumerate(rows):
        for x, bit in enumerate(row):
            if bit != '1':
                continue
            left, bottom = x * 128, (6-y) * 128
            pen.moveTo((left,bottom))
            pen.lineTo((left+128,bottom))
            pen.lineTo((left+128,bottom+128))
            pen.lineTo((left,bottom+128))
            pen.closePath()
    glyphs[names[ord(char)]] = pen.glyph()
fb.setupGlyf(glyphs)
metrics = {'.notdef': (768,0)}
for char, rows in patterns.items():
    columns = [x for row in rows for x, bit in enumerate(row) if bit == '1']
    metrics[names[ord(char)]] = (768, min(columns)*128 if columns else 0)
fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=896,descent=-128,lineGap=0)
fb.setupNameTable({'familyName':'FX Trend Pixel','styleName':'Regular','uniqueFontIdentifier':'FX Trend Pixel 1.0','fullName':'FX Trend Pixel Regular','psName':'FXTrendPixel-Regular','version':'Version 1.0'})
fb.setupOS2(sTypoAscender=896,sTypoDescender=-128,sTypoLineGap=0,usWinAscent=896,usWinDescent=128)
fb.setupPost()
fb.font.flavor='woff'
fb.font.save(root / 'FXTrendPixel.woff')
print(f"FXTrendPixel.woff: {(root / 'FXTrendPixel.woff').stat().st_size} bytes")
